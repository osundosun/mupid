package com.osundosun.mupid.api.event.enumerate;

/**
 * 이 재생에 어떻게 들어왔는가.
 *
 * <p>여기에 없는 값은 {@code normalize()} 가 **빈 문자열로 떨어뜨린다.** 400 이 아니라
 * 조용히 사라지므로, 프론트가 새 경로를 보내기 시작하면 이 enum 을 **먼저** 늘려야 한다.
 * 늦으면 그 사이 쌓인 이벤트는 경로 없이 원본 테이블에 박히고 되돌릴 수 없다.
 *
 * <p>`AUTOPLAY` 는 두지 않는다. 인플레이어 다음곡 추천이 없으므로 검색 결과를 이어 듣는
 * 것도 `SEARCH` 로 남겨야, 나중에 "검색 유입이었는데 추천이 정확했다" 를 구분해
 * 검색 노출 순서를 조정할 수 있다. 큐가 알아서 넘어간 재생은 `QUEUE` 다 — 그 순서를
 * 만든 것도 사용자이므로 추천이 한 선택으로 셀 수 없다.
 */
public enum EntryPath {

    RECOMMEND,
    SEARCH,
    PLAYLIST,

    /**
     * 재생 목록(큐)에서 다시 꺼낸 재생. 목록에서 직접 누른 것과 목록이 자동으로 넘긴 것
     * 모두다. 어느 화면에서 눌렀는지와 무관하다.
     */
    QUEUE,

    /**
     * '최근 들은 음악' 에서 다시 튼 재생. 홈과 프로필의 같은 섹션이 함께 쓴다.
     *
     * <p>{@code RECOMMEND} 와 반드시 갈라야 하는 값이다. 이미 아는 곡을 되꺼낸 것을
     * 추천 성과로 세면 추천 품질이 실제보다 좋아 보인다.
     */
    RECENT,

    /**
     * 아티스트 정보 패널에서 그 아티스트의 다른 곡을 찾아 튼 재생.
     *
     * <p>"이 아티스트의 다른 곡을 찾아 들었다" 는 아티스트 선호를 직접 드러내는 행동이다.
     * 패널이 모든 곡 줄에서 열려 화면으로 갈음하면 세 값으로 흩어졌다. 패널이 안에서
     * 검색 API 를 쓰더라도 사용자가 검색한 것은 아니므로 {@code SEARCH} 가 아니다.
     */
    ARTIST

}
