package com.osundosun.mupid.api.admin.service;

import com.osundosun.mupid.api.admin.response.AdminMusicTimelineResponse;

/**
 * 곡 하나의 가사·구간을 **시간축 위에 가로로** 그리기 위한 조회 (S15P21A204-380-B).
 *
 * <h2>왜 새 서비스인가 (기존 목록 조회로는 안 되는 것)</h2>
 *
 * 기존 {@link AdminResourceService#list} 는 자원 하나를 평평하게 준다. 요구는 셋인데 그중
 * 둘이 목록 조회만으로 안 된다.
 *
 * <ol>
 *   <li><b>여러 자원을 한 화면에 모은다.</b> 가사·구간 분석·구간-분위기는 각각 별도
 *       자원이라 목록 조회를 세 번 부르면 화면이 세 번 갈라진다.</li>
 *   <li><b>시간축의 최대값이 필요하다.</b> 행에서 유도하면 밴드가 잘렸을 때 축이 함께
 *       줄어들어 밴드마다 눈금이 달라진다. 그래서 DB 에서 집계한다.</li>
 *   <li><b>자기 시간 컬럼이 없는 자원이 있다.</b> 구간-분위기는 부모 구간에만 시간이 있어
 *       그 시간을 빌려 와야 같은 축 위에 놓인다.</li>
 * </ol>
 *
 * <p>그래도 **조회 자체는 목록 조회를 그대로 재사용한다.** 행의 모양(`_id`·`_labels`·
 * `_thumbnails`)이 같아야 화면이 같은 편집기를 쓸 수 있고, 필터·정렬 규약도 한 곳에만
 * 있어야 한다. 여기서 새로 만드는 것은 "여러 밴드를 묶는 일"과 "시간 키를 정규화하는 일"
 * 뿐이다.
 *
 * <h2>N+1 을 내지 않는다</h2>
 *
 * 밴드마다 질의가 한 번씩이고, 그 수는 **행 수와 무관**하다. 구간-분위기처럼 부모의 시간을
 * 빌리는 밴드는 부모 밴드를 이미 받아 두었으면 그 결과를 **재사용**한다 (캐시 키가 같다).
 */
public interface AdminTimelineService {

    /**
     * 곡 하나의 타임라인. 가사가 없거나 분석 전이어도 **404 가 아니다** — 행이 빈 밴드로
     * 오고, 시간 정보가 하나도 없으면 `hasTime` 이 false 다. 곡 자체가 없으면 404 다.
     */
    AdminMusicTimelineResponse timeline(int musicId);

}
